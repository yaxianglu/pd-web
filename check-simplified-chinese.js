function checkAndReplaceChinese(dir) {
  const files = fs.readdirSync(dir);
  
  files.forEach(file => {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);
    
    if (stat.isDirectory()) {
      checkAndReplaceChinese(filePath);
    } else if (file.endsWith('.jsx') || file.endsWith('.js') || file.endsWith('.tsx') || file.endsWith('.ts')) {
      try {
        let content = fs.readFileSync(filePath, 'utf8');
        let hasChanges = false;
        
        // 检查并替换简体中文
        Object.keys(simplifiedToTraditional).forEach(simplified => {
          const traditional = simplifiedToTraditional[simplified];
          if (content.includes(simplified)) {
            console.log(`在文件 ${filePath} 中找到简体中文: "${simplified}" -> "${traditional}"`);
            content = content.replace(new RegExp(simplified, 'g'), traditional);
            hasChanges = true;
          }
        });
        
        if (hasChanges) {
          fs.writeFileSync(filePath, content, 'utf8');
          console.log(`✅ 已更新文件: ${filePath}`);
        }
      } catch (error) {
        console.error(`❌ 处理文件 ${filePath} 时出错:`, error.message);
      }
    }
  });
}

